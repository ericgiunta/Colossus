  expect_no_error(e <- Residual(logitres, df, pearson = FALSE, deviance = TRUE))
  expect_equal(e$Deviance_Residual, abs(df$c - df$a * e$Probability) / (df$c - df$a * e$Probability) * sqrt(2 * (df$c * log((df$c + 1e-6) / (df$a * e$Probability)) + (df$a - df$c) * log((df$a - df$c + 1e-6) / (df$a - df$a * e$Probability)))), tolerance = 1e-4)
