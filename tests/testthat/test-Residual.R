  #
  expect_no_error(e <- Residual(model, df, pearson = FALSE, deviance = FALSE, a_n = a_n))
  expect_equal(e$Probability, c(0.25922510, 0.19781611, 0.14804720, 0.10909682, 0.07943855, 0.05732418, 0.04109128), tolerance = 1e-4)
  expect_no_error(e <- Residual(model, df, pearson = TRUE, deviance = FALSE, a_n = a_n))
  expect_equal(e$Pearson_Residual, (df$c - df$a * e$Probability) / sqrt(df$a * e$Probability * (1 - e$Probability)), tolerance = 1e-4)
  expect_no_error(e <- Residual(model, df, pearson = FALSE, deviance = TRUE, a_n = a_n))
